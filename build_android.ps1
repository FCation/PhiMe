# Build the Android (arm64-v8a) mod with the Windows LLVM toolchain. No NDK needed:
# the system libraries we link against are generated as tiny link-time stubs (the phone's real
# libc/libdl/liblog are used at runtime).
#   powershell -ExecutionPolicy Bypass -File mod\build_android.ps1 [-Serif Local|Source]
# Output: mod/out/android/libPhiMeMod.so  (the mod)
#         mod/out/android/libmain.so      (loader that replaces Unity's libmain.so)
# -Serif: see build_ios.ps1 (Local = your own font from serif.local.txt; Source = Source Serif 4, shareable)
param([ValidateSet("Local", "Source")][string]$Serif = "Local")
$ErrorActionPreference = "Stop"
$root = $PSScriptRoot
$llvm = "C:\Program Files\LLVM\bin"
$out = Join-Path $root "out\android"
$stubDir = Join-Path $out "stubs"
New-Item -ItemType Directory -Force $out, $stubDir | Out-Null

$target = "--target=aarch64-linux-android24"
$common = @($target, "-O2", "-fPIC", "-fno-exceptions", "-fno-rtti", "-funwind-tables", "-fno-stack-protector",
            "-fno-threadsafe-statics", "-nostdlib", "-Wall", "-mno-outline-atomics")
$link = @("-shared", "-fuse-ld=lld", "-Wl,-z,max-page-size=16384", "-Wl,--build-id", "-Wl,-z,noexecstack",
          "-Wl,--no-undefined", "-Wl,--gc-sections")

# ---- link-time stubs for system libraries ----
$stubs = @{
  "libc.so"   = "open read pread lseek write close mkdir rename unlink stat time snprintf vsnprintf strlen strcmp memcmp memcpy memmove memset calloc malloc realloc free qsort getenv usleep pthread_create pthread_detach"
  "libm.so"   = "cos sin sincos sincosf pow exp log ldexp"
  "libdl.so"  = "dlopen dlsym dlerror"
  "liblog.so" = "__android_log_print"
}
$stubLibs = @()
foreach ($name in $stubs.Keys) {
  $c = Join-Path $stubDir ($name + ".c")
  ($stubs[$name] -split ' ' | ForEach-Object { "void $_(void) {}" }) -join "`n" | Set-Content -Encoding ascii $c
  $so = Join-Path $stubDir $name
  & "$llvm\clang.exe" $target -w -shared -nostdlib -fPIC -fuse-ld=lld "-Wl,-soname,$name" $c -o $so
  if ($LASTEXITCODE -ne 0) { throw "stub $name failed" }
  $stubLibs += $so
}

# ---- the file picker's Java side (android/picker) -> a dex carried inside the mod ----
# Rebuilt only when a .java file is newer than picker_dex.inc (needs a JDK and build-tools' d8.jar).
$pk = Join-Path $root "android\picker"
$inc = Join-Path $pk "picker_dex.inc"
$java = Get-ChildItem $pk -Recurse -Filter *.java
if (-not (Test-Path $inc) -or ($java | Where-Object { $_.LastWriteTime -gt (Get-Item $inc).LastWriteTime })) {
  $jdk = (Get-ChildItem "C:\Program Files\Microsoft" -Directory -Filter "jdk-*" | Sort-Object Name | Select-Object -Last 1).FullName
  $d8 = Join-Path $env:LOCALAPPDATA "PhiMeTools\bt\android-14\lib\d8.jar"
  $jb = Join-Path $out "picker"
  Remove-Item -Recurse -Force $jb -ErrorAction SilentlyContinue
  New-Item -ItemType Directory -Force "$jb\stubs", "$jb\classes", "$jb\dex" | Out-Null
  & "$jdk\bin\javac.exe" --release 8 -encoding UTF-8 -nowarn -d "$jb\stubs" `
    (Get-ChildItem "$pk\stubs" -Recurse -Filter *.java | ForEach-Object { $_.FullName })
  if ($LASTEXITCODE -ne 0) { throw "picker stubs failed" }
  & "$jdk\bin\javac.exe" --release 8 -encoding UTF-8 -cp "$jb\stubs" -d "$jb\classes" `
    (Get-ChildItem "$pk\src" -Recurse -Filter *.java | ForEach-Object { $_.FullName })
  if ($LASTEXITCODE -ne 0) { throw "picker javac failed" }
  & "$jdk\bin\jar.exe" cf "$jb\stubs.jar" -C "$jb\stubs" .
  & "$jdk\bin\java.exe" -cp $d8 com.android.tools.r8.D8 --release --min-api 21 --lib "$jb\stubs.jar" `
    --output "$jb\dex" (Get-ChildItem "$jb\classes" -Recurse -Filter *.class | ForEach-Object { $_.FullName })
  if ($LASTEXITCODE -ne 0) { throw "picker d8 failed" }
  $bytes = [IO.File]::ReadAllBytes("$jb\dex\classes.dex")
  $sb = New-Object System.Text.StringBuilder
  [void]$sb.AppendLine("// generated by build_android.ps1 from android/picker/src (classes.dex, $($bytes.Length) bytes)")
  [void]$sb.Append("static const unsigned char kPickerDex[] = {")
  for ($i = 0; $i -lt $bytes.Length; $i++) {
    if ($i % 24 -eq 0) { [void]$sb.Append("`n") }
    [void]$sb.Append($bytes[$i]).Append(",")
  }
  [void]$sb.AppendLine("`n};")
  [IO.File]::WriteAllText($inc, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
  Write-Host "built $inc ($($bytes.Length) byte dex)"
}

# ---- the mod ----
$src = Get-ChildItem (Join-Path $root "src") -Filter *.cpp | ForEach-Object { $_.FullName }
# fonts embedded with .incbin (src/assets.cpp) need the assets folder's absolute path
$fontsDir = (Join-Path $root "assets\fonts").Replace('\', '/')
. (Join-Path $root "serif_font.ps1")
[IO.File]::WriteAllText((Join-Path $out "pm_assets.h"), (pmAssetsHeader $fontsDir $Serif))
$mod = Join-Path $out "libPhiMeMod.so"
& "$llvm\clang++.exe" @common "-std=c++17" "-fvisibility=hidden" "-nostdinc++" "-I$out" "-idirafter$(Join-Path $root 'src\third_party\libc')" @link "-Wl,-soname,libPhiMeMod.so" `
  @src @stubLibs -o $mod
if ($LASTEXITCODE -ne 0) { throw "mod build failed" }

# ---- the loader (new libmain.so) ----
$loader = Join-Path $out "libmain.so"
& "$llvm\clang++.exe" @common "-std=c++17" "-fvisibility=hidden" "-nostdinc++" @link "-Wl,-soname,libmain.so" `
  (Join-Path $root "android\loader.cpp") @stubLibs -o $loader
if ($LASTEXITCODE -ne 0) { throw "loader build failed" }

& "$llvm\llvm-strip.exe" --strip-unneeded $mod $loader
Write-Host "built $mod ($((Get-Item $mod).Length) bytes)"
Write-Host "built $loader ($((Get-Item $loader).Length) bytes)"
